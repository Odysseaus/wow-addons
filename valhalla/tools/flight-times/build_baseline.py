#!/usr/bin/env python3
"""Valhalla (1.2.60): the built-in flight times (Data/Forever/FlightData.lua: baseline) from exported times.

Input: text holding `["a>b>c"] = seconds,` lines, e.g. the ValhallaDB.flightExport block read (never copied)
from a player's SavedVariables, after /valhalla flighttimes export and a /reload; or a plain file of them.
Only the lines inside a ["times"] = { ... } block are read when there is one.

Each key must be an exact path of the game's flight master IDs: every node in FlightData's nodes, and
every leg one of its paths. The baseline keeps its times: a new key is added, a key it has is kept
(differences over --warn seconds listed), unless --replace. Run on the box only.

  python3 tools/flight-times/build_baseline.py export.txt [--data Valhalla/Data/Forever/FlightData.lua]
      [--replace] [--warn 20] [--dry-run]
"""
import argparse
import re
import sys

KEY = re.compile(r'\[\s*"(\d+(?:>\d+)+)"\s*\]\s*=\s*(\d+(?:\.\d+)?)')
NODE = re.compile(r'^\s*\[(\d+)\]\s*=\s*\{')
PATH = re.compile(r'^\s*\{\s*(\d+),\s*(\d+),')
START = "\t-- (1.2.60) built-in flight times"
END = "\t},  -- (end of baseline)"


def read_export(text):
    m = re.search(r'\["times"\]\s*=\s*\{(.*?)\n\s*\}', text, re.S)
    body = m.group(1) if m else text
    return {k: int(round(float(v))) for k, v in KEY.findall(body)}


def network(src):
    nodes, paths, part = set(), set(), None
    for line in src.splitlines():
        s = line.strip()
        if s.startswith("nodes = {"):
            part = "nodes"
        elif s.startswith("paths = {"):
            part = "paths"
        elif s.startswith("baseline = {"):
            part = None
        elif part == "nodes":
            m = NODE.match(line)
            if m:
                nodes.add(int(m.group(1)))
        elif part == "paths":
            m = PATH.match(line)
            if m:
                paths.add((int(m.group(1)), int(m.group(2))))
    return nodes, paths


def valid(key, nodes, paths):
    ids = [int(x) for x in key.split(">")]
    if any(i not in nodes for i in ids):
        return "a node not in FlightData"
    for a, b in zip(ids, ids[1:]):
        if (a, b) not in paths:
            return "%d>%d is not a path" % (a, b)
    return None


def current(src):
    i, j = src.find(START), src.find(END)
    if i < 0 or j < 0:
        return {}
    return {k: int(round(float(v))) for k, v in KEY.findall(src[i:j])}


def sort_key(k):
    return [int(x) for x in k.split(">")]


def block(times):
    lines = [START + ': seconds by the exact path of the game\'s flight master IDs ("a>b" one leg,',
             '\t-- "a>b>c" with stops), measured in game. Regenerated by tools/flight-times/build_baseline.py from',
             '\t-- /valhalla flighttimes export; read only (a learned time is ValhallaDB.worldmap.flightLearned).',
             "\tbaseline = {"]
    for k in sorted(times, key=sort_key):
        lines.append('\t\t["%s"] = %d,' % (k, times[k]))
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("export")
    ap.add_argument("--data", default="Valhalla/Data/Forever/FlightData.lua")
    ap.add_argument("--replace", action="store_true")
    ap.add_argument("--warn", type=int, default=20)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    src = open(a.data, encoding="utf-8").read()
    nodes, paths = network(src)
    have = current(src)
    new = read_export(open(a.export, encoding="utf-8").read())
    out, added, kept, replaced, bad = dict(have), [], [], [], []
    for k, v in sorted(new.items(), key=lambda kv: sort_key(kv[0])):
        why = valid(k, nodes, paths)
        if why:
            bad.append((k, why))
            continue
        if k not in have:
            out[k] = v
            added.append(k)
        elif a.replace and have[k] != v:
            out[k] = v
            replaced.append((k, have[k], v))
        elif abs(have[k] - v) > a.warn:
            kept.append((k, have[k], v))
    i, j = src.find(START), src.find(END)
    if i >= 0 and j >= 0:
        src = src[:i] + block(out) + src[j + len(END) + 1:]
    else:
        tail = src.rstrip().rfind("}")
        src = src[:tail] + block(out) + src[tail:]
    print("baseline: %d before, %d added, %d replaced, %d kept though off by more than %d s, %d rejected, %d after"
          % (len(have), len(added), len(replaced), len(kept), a.warn, len(bad), len(out)))
    for k, old, v in kept:
        print("  kept %s = %d (export says %d)" % (k, old, v))
    for k, old, v in replaced:
        print("  replaced %s: %d -> %d" % (k, old, v))
    for k, why in bad:
        print("  rejected %s: %s" % (k, why))
    if not a.dry_run:
        open(a.data, "w", encoding="utf-8").write(src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
