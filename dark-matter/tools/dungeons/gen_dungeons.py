#!/usr/bin/env python3
"""Generate DarkMatter/Data_Dungeons.lua (Adventure Guide static drop table).

Our own entries: seed.json is hand-authored (dungeons, boss order, NPC IDs). Per boss we keep the
boss-specific drops (not world drops, quality >= Uncommon, not quest items, >= 2% reported) from
the boss's Wowhead Classic NPC page (fallback source for drop attribution, cached in
wowhead_npc.json by fetch_wowhead.py; the Forever HTML pages are not reachable from our tooling).
Every NPC and item is then validated against Wowhead WoW Forever (primary source; tooltip API,
cached in wowhead_forever.json by verify_forever.py) and its Forever name / quality / icon is
used. Citations per entry: https://www.wowhead.com/forever/npc=<id>, https://www.wowhead.com/forever/item=<id>.
No other addon's loot table is used."""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "DarkMatter" / "Data_Dungeons.lua"
EXCLUDE = {21524, 21525}  # Winter Veil hats (seasonal world-event drops)
MIN_PCT = 0.02

def build(validate=True):
    seed = json.loads((HERE / "seed.json").read_text())
    npc = json.loads((HERE / "wowhead_npc.json").read_text())
    fv = json.loads((HERE / "wowhead_forever.json").read_text()) if (HERE / "wowhead_forever.json").exists() else {"npc": {}, "item": {}}
    picked = []
    for d in seed["dungeons"]:
        pd = dict(d, bosses=[])
        for b in d["bosses"]:
            page = npc[str(b[1])]
            assert page["title"] == b[0], (b, page["title"])
            drops = []
            for it in page["drops"]:
                if it.get("commondrop") or (it.get("quality") or 0) < 2 or it.get("classs") == 12: continue
                if not it.get("outof") or it["count"] / it["outof"] < MIN_PCT: continue
                if it["id"] in EXCLUDE or it["id"] >= 200000: continue  # >= 200000: Season of Discovery IDs
                drops.append(dict(it, pct=round(100.0 * it["count"] / it["outof"], 1)))
            drops.sort(key=lambda x: (-x["quality"], -x["pct"], x["name"]))
            pd["bosses"].append({"name": b[0], "npc": b[1], "rare": len(b) > 2 and b[2] == "rare", "drops": drops})
        picked.append(pd)
    if validate:
        for d in picked:
            for b in d["bosses"]:
                f = fv["npc"].get(str(b["npc"]))
                assert f and f["name"] == b["name"], ("NPC not validated on Wowhead Forever", b["npc"], b["name"], f)
                for it in b["drops"]:
                    f = fv["item"].get(str(it["id"]))
                    assert f and f["name"] == it["name"], ("item not validated on Wowhead Forever", it["id"], it["name"], f)
                    it["fq"], it["icon"] = f["quality"], f["icon"]
        seen = {}
        for d in picked:
            for b in d["bosses"]:
                ids = [it["id"] for it in b["drops"]]
                assert len(ids) == len(set(ids)), ("duplicate item on boss", b["name"])
                for i in ids: seen.setdefault(i, []).append(b["name"])
        names = [b["name"].lower() for d in picked for b in d["bosses"]]
        assert len(names) == len(set(names)), "duplicate boss names"
    return seed, picked

def lua(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    seed, picked = build(True)
    nb = sum(len(d["bosses"]) for d in picked); ni = sum(len(b["drops"]) for d in picked for b in d["bosses"])
    L = ["-- Dark Matter Adventure Guide: static drop table (generated by tools/dungeons/gen_dungeons.py; do not edit).",
         "-- Our own entries. Primary source: Wowhead WoW Forever (https://www.wowhead.com/forever/npc=<id>,",
         "-- https://www.wowhead.com/forever/item=<id>): every NPC and item below was validated there and uses its",
         "-- Forever name/quality/icon. Drop attribution fallback: Wowhead Classic NPC drop lists",
         "-- (https://www.wowhead.com/classic/npc=<id>), boss-specific drops only. Dungeons and bosses in the UI come",
         "-- from the live LFG data; this table only adds drops. Entries are gated with C_Item.DoesItemExistByID.",
         "-- %d dungeons, %d bosses, %d drops." % (len(picked), nb, ni),
         "local _, NS = ...", "", "NS.AdventureGuideSeed = {"]
    for d in picked:
        L.append("  { name = %s, short = %s, zone = %s, levels = { %d, %d }, wiki = %s, bosses = {" % (lua(d["name"]), lua(d["short"]), lua(d["zone"]), d["levels"][0], d["levels"][1], lua(d["wiki"])))
        for b in d["bosses"]:
            L.append("    { name = %s, npcId = %d,%s src = %s, dropSrc = %s, drops = {" % (lua(b["name"]), b["npc"], " rare = true," if b["rare"] else "",
                     lua("https://www.wowhead.com/forever/npc=%d" % b["npc"]), lua("https://www.wowhead.com/classic/npc=%d" % b["npc"])))
            for it in b["drops"]:
                L.append("      { itemId = %d, name = %s, quality = %d, icon = %s, pct = %s, src = %s }," % (it["id"], lua(it["name"]), it["fq"], lua("Interface\\Icons\\" + it["icon"]), it["pct"], lua("https://www.wowhead.com/forever/item=%d" % it["id"])))
            L.append("    } },")
        L.append("  } },")
    L.append("}")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, len(picked), "dungeons", nb, "bosses", ni, "drops")

if __name__ == "__main__":
    main()
