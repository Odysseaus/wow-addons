#!/usr/bin/env python3
"""Generate DarkMatter/Data_Dungeons.lua (Adventure Guide static drop table).

Our own entries: catalog.json is hand-authored (every Classic + Forever dungeon and raid, boss order, aliases);
resolve_forever.py confirms each instance and boss on Wowhead WoW Forever and writes seed.json. Per boss we keep the
boss-specific drops (not world drops, quality >= Uncommon, not quest items, >= 2% reported) from
the boss's Wowhead Classic NPC page (fallback source for drop attribution, cached in
wowhead_npc.json by fetch_wowhead.py; the Forever HTML pages are not reachable from our tooling).
Every NPC and item is then validated against Wowhead WoW Forever (primary source; tooltip API,
cached in wowhead_forever.json by verify_forever.py) and its Forever name / quality / icon is
used. Citations per entry: https://www.wowhead.com/forever/npc=<id>, https://www.wowhead.com/forever/item=<id>.
No other addon's loot table is used."""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "DarkMatter" / "Data_Dungeons.lua"
EXCLUDE = {21524, 21525}  # Winter Veil hats (seasonal world-event drops)
MIN_PCT = 0.02

NOT_ON_FOREVER, RENAMED = [], []

def build(validate=True):
    seed = json.loads((HERE / "seed.json").read_text())
    npc = json.loads((HERE / "wowhead_npc.json").read_text())
    fv = json.loads((HERE / "wowhead_forever.json").read_text()) if (HERE / "wowhead_forever.json").exists() else {"npc": {}, "item": {}}
    picked = []
    for d in seed["dungeons"]:
        pd = dict(d, bosses=[])
        for b in d["bosses"]:
            if not d.get("drops", True):
                pd["bosses"].append({"name": b[0], "npc": b[1], "rare": len(b) > 2 and b[2] == "rare", "drops": []})
                continue
            page = npc[str(b[1])]
            assert page["title"] == b[0], (b, page["title"])
            drops = []
            for it in page["drops"]:
                if it.get("commondrop") or (it.get("quality") or 0) < 2 or it.get("classs") == 12: continue
                if not it.get("outof") or it["count"] / it["outof"] < MIN_PCT: continue
                if it["id"] in EXCLUDE or it["id"] >= 200000: continue  # >= 200000: Season of Discovery IDs
                drops.append(dict(it, pct=round(100.0 * it["count"] / it["outof"], 1)))
            drops.sort(key=lambda x: (-x["quality"], -x["pct"], x["name"]))
            pd["bosses"].append({"name": b[0], "npc": b[1], "rare": len(b) > 2 and b[2] == "rare", "drops": drops})
        picked.append(pd)
    if validate:
        for d in picked:
            for b in d["bosses"]:
                f = fv["npc"].get(str(b["npc"]))
                assert f and f["name"] == b["name"], ("NPC not validated on Wowhead Forever", b["npc"], b["name"], f)
                keep = []
                for it in b["drops"]:
                    f = fv["item"].get(str(it["id"]))
                    assert str(it["id"]) in fv["item"], ("item not checked on Wowhead Forever (run verify_forever.py)", it["id"])
                    if not f:  # not in Wowhead Forever's database (yet): excluded, never seeded from Classic alone
                        NOT_ON_FOREVER.append(it["id"]); continue
                    if f["name"] != it["name"]: RENAMED.append((it["id"], it["name"], f["name"]))
                    it["name"], it["fq"], it["icon"] = f["name"], f["quality"], f["icon"]
                    keep.append(it)
                b["pending"] = bool(b["drops"]) and not keep  # had Classic drops, none on Forever yet
                b["drops"] = keep
        for d in picked:
            if d.get("drops", True) and not any(b["drops"] for b in d["bosses"]): d["drops"] = False
        seen = {}
        for d in picked:
            for b in d["bosses"]:
                ids = [it["id"] for it in b["drops"]]
                assert len(ids) == len(set(ids)), ("duplicate item on boss", b["name"])
                for i in ids: seen.setdefault(i, []).append(b["name"])
        for d in picked:
            names = [b["name"].lower() for b in d["bosses"]]
            assert len(names) == len(set(names)), ("duplicate boss names", d["name"])
    return seed, picked

def lua(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    seed, picked = build(True)
    nb = sum(len(d["bosses"]) for d in picked); ni = sum(len(b["drops"]) for d in picked for b in d["bosses"])
    nr = sum(1 for d in picked if d["kind"] == "Raid"); nds = sum(1 for d in picked if d["drops"])
    L = ["-- Dark Matter Adventure Guide: known-good dungeon/raid list + static drop table (generated by",
         "-- tools/dungeons/gen_dungeons.py from catalog.json; do not edit). Our own entries.",
         "-- Primary source: Wowhead WoW Forever. Instances: https://www.wowhead.com/forever/zone=<id> (name, level range,",
         "-- type, location; wing ranges and Forever-only instances not yet in the zone data cite levelSrc). Bosses:",
         "-- https://www.wowhead.com/forever/npc=<id>. Items: https://www.wowhead.com/forever/item=<id> (Forever name/quality/icon).",
         "-- Drop attribution fallback: Wowhead Classic NPC drop lists (https://www.wowhead.com/classic/npc=<id>), boss-specific",
         "-- drops only. dropsSeeded = false: boss list only, drops in a later build. Items are gated with C_Item.DoesItemExistByID.",
         "-- %d instances (%d dungeons, %d raids), %d bosses, %d drops (drops seeded for %d dungeons)." % (len(picked), len(picked) - nr, nr, nb, ni, nds),
         "-- %d Classic drop entries (%d unique items) are not in Wowhead Forever's database yet and are left out; %d use their Forever name." % (len(NOT_ON_FOREVER), len(set(NOT_ON_FOREVER)), len(RENAMED)),
         "local _, NS = ...", "", "NS.AdventureGuideSeed = {"]
    for d in picked:
        extra = ""
        if d.get("aliases"): extra += " aliases = { %s }," % ", ".join(lua(a) for a in d["aliases"])
        if d.get("forever"): extra += " forever = true,"
        if d.get("bossSrc"): extra += " bossSrc = %s," % lua(d["bossSrc"])
        L.append("  { name = %s, short = %s, kind = %s, size = %d, zone = %s, levels = { %d, %d }, dropsSeeded = %s,%s src = %s, levelSrc = %s, bosses = {" % (
            lua(d["name"]), lua(d["short"]), lua(d["kind"]), d["size"], lua(d["zone"]), d["levels"][0], d["levels"][1],
            "true" if d["drops"] else "false", extra, lua(d["src"]), lua(d["levelSrc"])))
        for b in d["bosses"]:
            if not d["drops"]:
                L.append("    { name = %s, npcId = %d,%s src = %s, drops = {} }," % (lua(b["name"]), b["npc"], " rare = true," if b["rare"] else "",
                         lua("https://www.wowhead.com/forever/npc=%d" % b["npc"])))
                continue
            L.append("    { name = %s, npcId = %d,%s%s src = %s, dropSrc = %s, drops = {" % (lua(b["name"]), b["npc"], " rare = true," if b["rare"] else "", " dropsPending = true," if b.get("pending") else "",
                     lua("https://www.wowhead.com/forever/npc=%d" % b["npc"]), lua("https://www.wowhead.com/classic/npc=%d" % b["npc"])))
            for it in b["drops"]:
                L.append("      { itemId = %d, name = %s, quality = %d, icon = %s, pct = %s, src = %s }," % (it["id"], lua(it["name"]), it["fq"], lua("Interface\\Icons\\" + it["icon"]), it["pct"], lua("https://www.wowhead.com/forever/item=%d" % it["id"])))
            L.append("    } },")
        L.append("  } },")
    L.append("}")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, len(picked), "instances", nr, "raids", nb, "bosses", ni, "drops", nds, "drop-seeded;", len(NOT_ON_FOREVER), "drop entries not on Forever left out", len(set(NOT_ON_FOREVER)), "items; renamed", RENAMED)

if __name__ == "__main__":
    main()
